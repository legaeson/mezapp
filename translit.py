# 4. Долгие гласные
# ------------------------------------------------------------

LONG_VOWELS = {
    "аа": "ā",
    "Аа": "Ā",
    "АА": "Ā",
}

MAZIN_LONG_VOWELS = {
    "аьаь": "ǣ",
    "Аьаь": "Ǣ",
    "АЬАЬ": "Ǣ",
}


# ------------------------------------------------------------
# Компилируем всё один раз.
# ------------------------------------------------------------

def make_pattern(mapping: dict[str, str]) -> re.Pattern:
    keys = sorted(mapping.keys(), key=len, reverse=True)
    return re.compile("|".join(re.escape(k) for k in keys))


SPECIAL_PATTERN = make_pattern(REPLACEMENTS)
LETTER_PATTERN = make_pattern(LETTERS)
LONG_PATTERN = make_pattern(LONG_VOWELS)
MAZIN_LONG_PATTERN = make_pattern(MAZIN_LONG_VOWELS)


# ------------------------------------------------------------
# Быстрая замена через словарь
# ------------------------------------------------------------

def replace_with_dict(
    text: str,
    pattern: re.Pattern,
    mapping: dict[str, str],
) -> str:
    return pattern.sub(lambda m: mapping[m.group(0)], text)


# ------------------------------------------------------------
# Основная функция
# ------------------------------------------------------------

def transliterate(
    text: str,
    mazin: bool = False,
) -> str:

    if not text:
        return text

    # 1. 1 / l / L / | / I / i / ӏ -> Ӏ (нормализация в контексте кириллицы)
    text = normalize(text)

    # 2. Mazin: длинные гласные
    if mazin:
        text = replace_with_dict(
            text,
            MAZIN_LONG_PATTERN,
            MAZIN_LONG_VOWELS,
        )

    # 3. Общая долгота
    text = replace_with_dict(
        text,
        LONG_PATTERN,
        LONG_VOWELS,
    )

    # 4. Позиционная замена для буквы Я / я
    text = replace_ya(text)

    # 5. Специальные сочетания
    text = replace_with_dict(
        text,
        SPECIAL_PATTERN,
        REPLACEMENTS,
    )

    # 6. Одиночные буквы
    text = replace_with_dict(
        text,
        LETTER_PATTERN,
        LETTERS,
    )

    # 7. Остаточная палочка
    text = text.replace("Ӏ", "'")

    return text


