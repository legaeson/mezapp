# ------------------------------------------------------------
# 3.1 Позиционная замена для буквы Я / я
# В начале слова, после гласных и разделительных знаков (ъ, ь) -> ya / Ya
# После согласных -> æ / Æ
# ------------------------------------------------------------

VOWELS_AND_SIGNS = set("аеёиоуыэюяАЕЁИОУЫЭЮЯъьЪЬāǣĀǢaeyioɨuüöæAEYIOƗUÜÖÆ")

def replace_ya(text: str) -> str:
    if not text:
        return text

    res = []
    for i, char in enumerate(text):
        if char in ('я', 'Я'):
            prev_idx = i - 1
            if prev_idx >= 0 and text[prev_idx] in ('Ӏ', 'ӏ', "'"):
                prev_idx -= 1

            if prev_idx < 0:
                prev_char = ''
            else:
                prev_char = text[prev_idx]

            if not prev_char or not prev_char.isalpha() or prev_char in VOWELS_AND_SIGNS:
                res.append('Ya' if char == 'Я' else 'ya')
            else:
                res.append('Æ' if char == 'Я' else 'æ')
        else:
            res.append(char)
    return "".join(res)


