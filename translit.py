# ------------------------------------------------------------
# 1. Нормализация палочки
# 1, l, L, |, I, i, ӏ, І, і -> Ӏ
# В сочетании с кириллицей (абруптивные, фарингализованные звуки)
# ------------------------------------------------------------

def normalize(text: str) -> str:
    if not text:
        return text

    # 1. Замена палочки после кириллических букв и надстрочных знаков
    text = re.sub(r"([а-яА-ЯёЁӀӏ][\u0300-\u036f˚]*)[1lLIi|ӏІі]", r"\1Ӏ", text)
    # 2. Замена палочки перед кириллическими буквами в начале слов
    text = re.sub(r"(^|[\s\b])[1lLIi|ӏІі](?=[а-яА-ЯёЁ])", r"\1Ӏ", text)
    # 3. Прямая замена оставшихся палочек
    return text.translate({
        ord("1"): "Ӏ",
        ord("l"): "Ӏ",
        ord("L"): "Ӏ",
        ord("|"): "Ӏ",
        ord("I"): "Ӏ",
        ord("i"): "Ӏ",
        ord("ӏ"): "Ӏ",
        ord("І"): "Ӏ",
        ord("і"): "Ӏ",
    })


